import type { PromptType } from './db.js';

export interface PromptItem {
  id: string;
  type: PromptType;
  rating: 'pg' | 'pg13';
  text: string;
}

function list(type: PromptType, rating: 'pg' | 'pg13', texts: string[]): PromptItem[] {
  return texts.map((text, i) => ({
    id: `${type}:${rating}:${i + 1}`,
    type,
    rating,
    text,
  }));
}

